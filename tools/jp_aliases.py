def with_aliases(code, readings):
    """読みがなの欄（| 区切り）に通称を足して返す"""
    items = [r for r in readings.split("|") if r]
    for a in ALIASES.get(code, []):
        if a not in items:
            items.append(a)
    return "|".join(items)
