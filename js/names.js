export function lookupName(code) {
  return JP_NAMES[code] || '';
}

const norm = (s) => s.normalize('NFKC').toLowerCase().replace(/\s/g, '');

export function searchLocal(q) {
  const n = norm(q);
  if (!n) return [];
  return Object.entries(JP_NAMES)
    .filter(([code, name]) => code.startsWith(n) || norm(name).includes(n))
    .slice(0, 10)
    .map(([code, name]) => ({ code, name, source: '辞書' }));
}
